// Comfy Desktop model folders for workflow setup (electron/comfyModelPaths.cjs):
// the per-installation YAML is found from the chosen ComfyUI folder, its
// is_default folder receives downloads, and plain installs are unchanged.
import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const {
  findComfyDesktopModelPathConfig, loadComfyModelPaths, parseExtraModelPathConfig, resolveModelDownloadFolder,
} = require('../electron/comfyModelPaths.cjs')

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ds-comfy-model-paths-'))
test.after(() => fs.rmSync(tmp, { recursive: true, force: true }))

const appData = path.join(tmp, 'AppData', 'Roaming')
const installPath = path.join(tmp, 'Comfy-Desktop', 'ComfyUI-Installs', 'JAY')
const comfyRoot = path.join(installPath, 'ComfyUI')
const shared = path.join(tmp, 'F', '....CONFY UI (DO  NOT DELETE)', 'SHARED MODELS')
const desktopDir = path.join(appData, 'Comfy Desktop')
const desktopYaml = path.join(desktopDir, 'instance-model-paths', 'inst-1789526138831.yaml')

fs.mkdirSync(path.join(comfyRoot, 'models'), { recursive: true })
fs.mkdirSync(path.dirname(desktopYaml), { recursive: true })
fs.mkdirSync(shared, { recursive: true })
fs.writeFileSync(path.join(desktopDir, 'installations.json'), JSON.stringify([
  { id: '../escape', name: 'Bad', installPath },
  { id: 'inst-1789526138831', name: 'JAY', installPath },
  { id: 'inst-1789526010371', name: 'Comfy Cloud', status: 'installed' },
]))
// Shape Comfy Desktop writes (multi-line values, quoted keys, Windows path).
fs.writeFileSync(desktopYaml, [
  '# Generated by Comfy Desktop — do not edit manually.',
  'comfy.desktop_0:',
  `  base_path: '${shared.replace(/'/g, "''")}'`,
  '  is_default: true',
  "  'checkpoints': 'checkpoints/'",
  "  'controlnet': |-",
  '    controlnet/',
  '    t2i_adapter/',
  "  'text_encoders': 'text_encoders/'",
  "  'diffusion_models': 'diffusion_models/'",
  '',
].join('\r\n'))

test('finds the Comfy Desktop config from the ComfyUI folder or the install folder', async () => {
  for (const root of [comfyRoot, installPath, `${comfyRoot}${path.sep}`]) {
    const found = await findComfyDesktopModelPathConfig(root, { appDataDir: appData })
    assert.equal(found?.configPath, desktopYaml, root)
    assert.equal(found.installationName, 'JAY')
  }
  assert.equal(await findComfyDesktopModelPathConfig(path.join(tmp, 'OtherComfy'), { appDataDir: appData }), null)
  assert.equal(await findComfyDesktopModelPathConfig(comfyRoot, { appDataDir: path.join(tmp, 'nowhere') }), null)
})

test('downloads go to the shared default folder; checks see every folder', async () => {
  const paths = await loadComfyModelPaths(comfyRoot, { appDataDir: appData })
  assert.deepEqual(paths.configPaths, [desktopYaml])
  assert.equal(paths.defaultBasePath, path.normalize(shared))
  assert.deepEqual(paths.pathsByKey.get('controlnet'), [path.join(shared, 'controlnet'), path.join(shared, 't2i_adapter')])
  assert.equal(paths.pathCount, 5)

  const modelsPath = path.join(comfyRoot, 'models')
  const resolve = (targetSubdir) => resolveModelDownloadFolder({ modelsPath, targetSubdir, defaultDirsByKey: paths.defaultDirsByKey })
  assert.equal(resolve('checkpoints'), path.join(shared, 'checkpoints'))
  assert.equal(resolve('text_encoders'), path.join(shared, 'text_encoders'))
  assert.equal(resolve('diffusion_models/wan'), path.join(shared, 'diffusion_models', 'wan'))
  assert.equal(resolve('controlnet'), path.join(shared, 'controlnet'), 'first folder of a multi-line key')
  // Keys the shared folder does not map stay in ComfyUI's own folder, where ComfyUI looks.
  assert.equal(resolve('frame_interpolation'), path.join(modelsPath, 'frame_interpolation'))
  assert.equal(resolve(''), modelsPath)
  assert.equal(resolve('checkpoints/../../escape'), modelsPath)
})

test('a plain ComfyUI keeps <root>/models; its own extra_model_paths.yaml still counts', async () => {
  const plainRoot = path.join(tmp, 'PlainComfy')
  fs.mkdirSync(path.join(plainRoot, 'models'), { recursive: true })
  const noExtras = await loadComfyModelPaths(plainRoot, { appDataDir: appData })
  assert.equal(noExtras.defaultBasePath, '')
  assert.equal(resolveModelDownloadFolder({ modelsPath: path.join(plainRoot, 'models'), targetSubdir: 'vae', defaultDirsByKey: noExtras.defaultDirsByKey }), path.join(plainRoot, 'models', 'vae'))

  fs.writeFileSync(path.join(plainRoot, 'extra_model_paths.yaml'), 'a1111:\n  base_path: ../sd\n  checkpoints: models/Stable-diffusion\n')
  const withA1111 = await loadComfyModelPaths(plainRoot, { appDataDir: appData })
  assert.deepEqual(withA1111.pathsByKey.get('checkpoints'), [path.join(tmp, 'sd', 'models', 'Stable-diffusion')])
  assert.equal(withA1111.defaultDirsByKey.size, 0, 'not is_default, so downloads stay in <root>/models')
})

test('the Comfy Desktop default wins over a root extra_model_paths.yaml default (ComfyUI load order)', async () => {
  const rootYaml = path.join(comfyRoot, 'extra_model_paths.yaml')
  fs.writeFileSync(rootYaml, `other:\n  base_path: ${JSON.stringify(path.join(tmp, 'other'))}\n  is_default: true\n  checkpoints: ckpts\n  loras: loras\n`)
  try {
    const paths = await loadComfyModelPaths(comfyRoot, { appDataDir: appData })
    assert.deepEqual(paths.configPaths, [rootYaml, desktopYaml])
    assert.equal(paths.defaultDirsByKey.get('checkpoints'), path.join(shared, 'checkpoints'))
    assert.equal(paths.pathsByKey.get('checkpoints').length, 2)
    assert.equal(paths.defaultDirsByKey.has('loras'), false)
  } finally {
    fs.rmSync(rootYaml)
  }
})

test('parser: environment variables, relative paths and bad files', async () => {
  const configPath = path.join(tmp, 'cfg', 'extra.yaml')
  const parsed = parseExtraModelPathConfig('x:\n  base_path: "%MODELS%"\n  is_default: "true"\n  vae: vae\ny:\n  loras: ./rel\n', configPath, { env: { MODELS: path.join(tmp, 'm') } })
  assert.equal(parsed.defaultDirsByKey.get('vae'), path.join(tmp, 'm', 'vae'))
  assert.deepEqual(parsed.pathsByKey.get('loras'), [path.join(tmp, 'cfg', 'rel')])
  assert.equal(parseExtraModelPathConfig('- just\n- a list\n', configPath).warnings.length, 1)

  const brokenRoot = path.join(tmp, 'Broken')
  fs.mkdirSync(brokenRoot, { recursive: true })
  fs.writeFileSync(path.join(brokenRoot, 'extra_model_paths.yaml'), 'a: [unclosed')
  const broken = await loadComfyModelPaths(brokenRoot, { appDataDir: appData })
  assert.equal(broken.pathCount, 0)
  assert.match(broken.warnings[0], /Could not read extra_model_paths\.yaml/)
})

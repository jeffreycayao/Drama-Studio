// Run against a local Vite server; requires Playwright and Chrome.
// PLAYWRIGHT_MODULE_PATH and CHROME_PATH can select existing local runtimes.
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/usr/bin/google-chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto((process.env.VELORN_TEST_URL || 'http://127.0.0.1:5184') + '/tests/fixtures/editor-controls.html')
    await page.getByRole('button', { name: 'Fit clip', exact: true }).waitFor()
    const state = () => page.evaluate(() => { const s = window.editorControlsTest.timeline.getState(); return { rate: s.playbackRate, playing: s.isPlaying, time: s.playheadPosition, zoom: s.zoom } })
    const before = await state()
    for (const rate of [0.5, 0.25, 0.125, 0.125]) {
      await page.keyboard.press('Shift+L')
      assert.equal((await state()).rate, rate)
    }
    const start = await state()
    await page.waitForTimeout(500)
    const delta = (await state()).time - start.time
    assert.ok(delta > 0.025 && delta < 0.15, `1/8x clock advances continuously: ${delta}`)
    await page.keyboard.press('L')
    assert.equal((await state()).rate, 1)
    for (const rate of [-0.5, -0.25, -0.125]) {
      await page.keyboard.press('Shift+J')
      assert.equal((await state()).rate, rate)
    }
    await page.keyboard.press('K')
    assert.equal((await state()).playing, false)
    await page.keyboard.press('Control+Shift+L')
    assert.equal((await state()).playing, false)
    await page.getByRole('textbox', { name: 'Typing guard' }).fill('JKL')
    assert.equal((await state()).playing, false)
    await page.getByRole('textbox', { name: 'Typing guard' }).blur()
    await page.keyboard.down('k')
    await page.keyboard.press('l')
    await page.keyboard.up('k')
    assert.equal((await state()).rate, 0.5)
    await page.keyboard.press('K')
    console.log('PASS: real transport handlers, slow forward/reverse, clock, fast reset, K chord and typing/modifier guards')

    const viewport = page.getByTestId('keyframe-viewport')
    const metrics = () => viewport.evaluate(el => ({ left: el.scrollLeft, width: el.clientWidth, content: el.scrollWidth }))
    const fit = await metrics()
    assert.ok(fit.content <= fit.width + 2, 'initial clip fits')
    for (let i = 0; i < 2; i++) await page.getByRole('button', { name: 'Zoom in keyframes', exact: true }).click()
    assert.ok((await metrics()).content > fit.content * 2, 'zoom spreads keys')
    assert.equal((await state()).zoom, before.zoom, 'main timeline zoom unchanged')
    await viewport.evaluate(el => { el.scrollLeft = 150 })
    const wheelBefore = await metrics()
    const rect = await viewport.boundingBox()
    await page.mouse.move(rect.x + 448, rect.y + 100)
    await page.keyboard.down('Control')
    await page.mouse.wheel(0, -70)
    await page.keyboard.up('Control')
    await page.waitForTimeout(100)
    const wheelAfter = await metrics()
    const oldScale = (wheelBefore.content - 158) / 10
    const newScale = (wheelAfter.content - 158) / 10
    assert.ok(newScale > oldScale)
    assert.ok(Math.abs((wheelBefore.left + 300) / oldScale - (wheelAfter.left + 300) / newScale) < 0.02, 'pointer time preserved')
    // Drag an isolated key by one second at the new scale, then undo it.
    const key = page.locator('[title^="Position X:"][title*="at 2.00s"]')
    await key.scrollIntoViewIfNeeded()
    const keyBox = await key.boundingBox()
    const laneScale = await key.evaluate(el => parseFloat(el.parentElement.style.width) / 10)
    await page.mouse.move(keyBox.x + keyBox.width / 2, keyBox.y + keyBox.height / 2)
    await page.mouse.down()
    await page.mouse.move(keyBox.x + keyBox.width / 2 + laneScale, keyBox.y + keyBox.height / 2, { steps: 8 })
    await page.mouse.up()
    const dragged = await page.evaluate(() => window.editorControlsTest.timeline.getState().clips[0].keyframes.positionX.find(k => k.value === 60).time)
    assert.equal(dragged, 3, 'drag maps through zoom and snaps to frames')
    await page.keyboard.press('Control+z')
    assert.equal(await page.evaluate(() => window.editorControlsTest.timeline.getState().clips[0].keyframes.positionX.find(k => k.value === 60).time), 2)
    console.log('PASS: zoomed keyframe drag and undo')
    await page.getByRole('button', { name: 'Fit clip', exact: true }).click()
    assert.equal((await metrics()).left, 0)
    await page.setViewportSize({ width: 1000, height: 720 })
    await page.waitForTimeout(100)
    const resized = await metrics()
    assert.ok(resized.content <= resized.width + 2, 'Fit follows panel resizing')
    await page.getByRole('button', { name: 'Zoom in keyframes', exact: true }).click()
    await page.evaluate(() => window.editorControlsTest.timeline.setState(s => ({ clips: [...s.clips, { ...s.clips[0], id: 'other', duration: 20 }], selectedClipIds: ['other'] })))
    await page.waitForTimeout(100)
    assert.equal((await metrics()).left, 0)
    assert.ok((await metrics()).content <= (await metrics()).width + 2, 'new selection fits')
    if (process.env.VELORN_TEST_SCREENSHOT) await page.screenshot({ path: process.env.VELORN_TEST_SCREENSHOT })
    assert.deepEqual(errors, [])
    console.log('PASS: independent zoom, pointer anchor, Fit, resize, selection reset; no renderer exceptions')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
